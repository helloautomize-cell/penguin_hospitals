import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await b.newPage();
const posts = [];
p.on("request", (r) => { if (r.method() === "POST") posts.push(r.url()); });
await p.goto("http://localhost:3000/book/", { waitUntil: "networkidle" });
await p.waitForTimeout(3500);
await p.getByLabel("Patient name").fill("Test");
await p.getByLabel("Mobile").fill("9876543210");
await p.getByLabel("Age").fill("10");
await p.getByRole("checkbox", { name: /agree that Penguin Hospital/ }).check();
await p.getByRole("button", { name: "Request an appointment" }).click();
await p.waitForTimeout(2000);
console.log("after submit 1:", posts.length, await p.getByRole("alert").first().textContent().catch(() => "none"));
await p.getByRole("checkbox", { name: /patient is under 18/i }).check();
await p.waitForTimeout(500);
await p.getByRole("button", { name: "Request an appointment" }).click();
await p.waitForTimeout(2500);
console.log("after submit 2:", posts.length, await p.getByRole("alert").first().textContent().catch(() => "none"));
console.log("posts:", posts);
await b.close();
